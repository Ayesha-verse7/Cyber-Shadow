"""
cyber_shadow.cracker
======================

Educational Dictionary Cracker.

This module demonstrates, for learning purposes only, how a simple
dictionary attack works against a hashed password:

    1. Read candidate words from a LOCAL wordlist file.
    2. Hash each candidate with the same algorithm as the target hash.
    3. Compare the computed hash to the target hash.
    4. Stop as soon as a match is found (or the list is exhausted).

Scope / Safety:
    - This module only ever compares against a hash that was
      generated BY THIS APPLICATION and stored locally via
      `cyber_shadow.storage`.
    - It only reads candidate words from a local wordlist file that
      ships with this project (data/test_wordlist.txt) or another
      file the user explicitly points it at on their own machine.
    - It performs no network access whatsoever.

The results include the number of attempts made and the elapsed
wall-clock time, so the user can see concretely how dictionary
attacks scale with wordlist size.
"""

from __future__ import annotations

import os
import time
from dataclasses import dataclass
from typing import List, Optional

from cyber_shadow.hashing import generate_hash, SUPPORTED_ALGORITHMS

DEFAULT_WORDLIST_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data",
    "test_wordlist.txt",
)


@dataclass
class CrackResult:
    """Outcome of a dictionary-cracking attempt."""

    found: bool
    matched_password: Optional[str]
    attempts: int
    total_candidates: int
    elapsed_seconds: float
    algorithm: str

    @property
    def attempts_per_second(self) -> float:
        if self.elapsed_seconds <= 0:
            return float(self.attempts)
        return self.attempts / self.elapsed_seconds


def load_wordlist(path: str = DEFAULT_WORDLIST_PATH) -> List[str]:
    """
    Load candidate passwords from a local wordlist file, one
    candidate per line. Blank lines and surrounding whitespace are
    stripped; duplicate lines are preserved in file order (no
    reordering) but exact duplicates are removed to avoid double
    counting attempts.

    Raises
    ------
    FileNotFoundError
        If the wordlist file does not exist.
    OSError
        If the file cannot be read.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Wordlist file not found: '{path}'. "
            "Make sure data/test_wordlist.txt exists, or provide a valid path."
        )

    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            raw_lines = f.readlines()
    except OSError as exc:
        raise OSError(f"Could not read wordlist file '{path}': {exc}") from exc

    seen = set()
    candidates = []
    for line in raw_lines:
        word = line.strip()
        if not word or word in seen:
            continue
        seen.add(word)
        candidates.append(word)

    return candidates


def crack_hash(
    target_hash: str,
    algorithm: str = "sha1",
    wordlist_path: str = DEFAULT_WORDLIST_PATH,
    progress_callback=None,
) -> CrackResult:
    """
    Attempt to find a candidate word whose hash matches `target_hash`.

    Parameters
    ----------
    target_hash : str
        The hex digest to try to match (must have been generated by
        this same application's hashing module).
    algorithm : str
        "md5" or "sha1" - must match the algorithm used to create
        the target hash.
    wordlist_path : str
        Path to a local newline-separated wordlist file.
    progress_callback : callable, optional
        If provided, called as progress_callback(attempts, candidate)
        after every attempt - useful for live progress display.

    Returns
    -------
    CrackResult

    Raises
    ------
    ValueError
        If target_hash is empty or algorithm is unsupported.
    FileNotFoundError
        If the wordlist file cannot be found.
    """
    if not target_hash or not isinstance(target_hash, str):
        raise ValueError("target_hash must be a non-empty string.")

    algo = algorithm.strip().lower()
    if algo not in SUPPORTED_ALGORITHMS:
        raise ValueError(
            f"Unsupported algorithm '{algorithm}'. "
            f"Supported algorithms: {', '.join(SUPPORTED_ALGORITHMS)}."
        )

    target_hash = target_hash.strip().lower()
    candidates = load_wordlist(wordlist_path)
    total_candidates = len(candidates)

    attempts = 0
    matched_password = None

    start_time = time.perf_counter()
    for candidate in candidates:
        attempts += 1
        computed = generate_hash(candidate, algo)

        if progress_callback is not None:
            progress_callback(attempts, candidate)

        if computed == target_hash:
            matched_password = candidate
            break
    elapsed = time.perf_counter() - start_time

    return CrackResult(
        found=matched_password is not None,
        matched_password=matched_password,
        attempts=attempts,
        total_candidates=total_candidates,
        elapsed_seconds=elapsed,
        algorithm=algo,
    )


def format_crack_report(result: CrackResult) -> str:
    """Build a readable multi-line summary of a CrackResult."""
    lines = []
    lines.append("Dictionary Attack Report")
    lines.append("-" * 40)
    lines.append(f"Algorithm         : {result.algorithm.upper()}")
    lines.append(f"Wordlist size     : {result.total_candidates} candidate(s)")
    lines.append(f"Attempts made     : {result.attempts}")
    lines.append(f"Elapsed time      : {result.elapsed_seconds:.6f} seconds")
    lines.append(f"Attempts / second : {result.attempts_per_second:,.2f}")

    if result.found:
        lines.append(f"Result            : MATCH FOUND -> '{result.matched_password}'")
    else:
        lines.append("Result            : NO MATCH - password not in wordlist.")

    lines.append("-" * 40)
    return "\n".join(lines)
